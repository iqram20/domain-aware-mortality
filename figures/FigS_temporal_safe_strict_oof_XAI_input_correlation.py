def compress_words(

    text: str,

    front: int = 4,

    back: int = 2,

) -> str:

    words = str(text).split()



    if len(words) <= front + back + 1:

        return str(text)



    return (

        " ".join(words[:front])

        + " … "

        + " ".join(words[-back:])

    )





