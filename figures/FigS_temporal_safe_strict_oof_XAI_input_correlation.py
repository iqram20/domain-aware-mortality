def reconstruct_current_run(

    module,

    run_dir: pathlib.Path,

    data_path: pathlib.Path,

) -> Dict[str, Any]:

    config = load_json(run_dir / "config.json")



    configured_data_path = pathlib.Path(

        str(config.get("data_path", data_path))

    )



    if (

        data_path == DEFAULT_DATA_PATH

        and configured_data_path.exists()

    ):

        data_path = configured_data_path



    print("\n" + "=" * 100)

    print("RECONSTRUCTING STRICT-OOF COHORT AND SAVED TEST ORDER")

    print("=" * 100)



    source = pd.read_csv(

        require_file(data_path),

        low_memory=False,

    )



    cohort, cohort_flow = module.apply_reviewer_cohort_exclusions(

        source,

        target_column=str(

            config.get("target_column", "mortality_30d")

        ),

        exclude_asa6=bool(

            config.get("exclude_asa6", True)

        ),

    )



    if bool(config.get("add_interactions", True)):

        cohort = module.add_mortality_interactions(cohort)


    X_raw = module.extract_model_features_classification(

        cohort,

        verbose=False,

    )



    target_column = str(

        config.get("target_column", "mortality_30d")

    )



    y_all = (

        cohort.loc[X_raw.index, target_column]

        .astype(int)

        .to_numpy()

    )



    X_raw = module.clean_raw_predictors(X_raw)



    test_predictions = pd.read_csv(

        require_file(

            run_dir / "test_predictions_all_models.csv"

        )

    )



    required_columns = {

        "final_cohort_row_position",

        "source_row_position",

        "y_true",

    }



    missing = required_columns - set(test_predictions.columns)



    if missing:

        raise KeyError(

            "test_predictions_all_models.csv lacks columns: "

            f"{sorted(missing)}"

        )



    test_positions = (

        test_predictions["final_cohort_row_position"]

        .astype(int)

        .to_numpy()

    )



    X_test_raw = (

        X_raw.iloc[test_positions]

        .reset_index(drop=True)

    )



    y_test = y_all[test_positions]



    if not np.array_equal(

        y_test,

        test_predictions["y_true"].astype(int).to_numpy(),

    ):

        raise RuntimeError(

            "Reconstructed outcomes do not match the saved test predictions."

        )



    print(cohort_flow.to_string(index=False))

    print(f"Test encounters: {len(y_test):,}")

    print(f"Test deaths:     {int(y_test.sum()):,}")

    print(f"Raw predictors:  {X_raw.shape[1]:,}")



    return {

        "config": config,

        "data_path": data_path,

        "X_test_raw": X_test_raw,

        "y_test": y_test,

        "test_predictions": test_predictions,

    }





