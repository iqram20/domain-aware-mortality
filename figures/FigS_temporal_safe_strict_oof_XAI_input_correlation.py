def transformed_matrix_for_fold(

    raw_frame: pd.DataFrame,

    preprocessor,

    variance_selector,

    selected_indices: np.ndarray,

) -> np.ndarray:

    matrix = preprocessor.transform(raw_frame)



    matrix = np.nan_to_num(

        matrix,

        nan=0.0,

        posinf=0.0,

        neginf=0.0,

    ).astype(np.float32)



    matrix = variance_selector.transform(

        matrix

    ).astype(np.float32)



    return matrix[:, selected_indices].astype(np.float32)





def feature_domain_map_from_metadata(

    feature_names: np.ndarray,

    metadata: Mapping[str, Any],

) -> Dict[str, str]:

    output: Dict[str, str] = {}



    for domain, indices in metadata.get(

        "domain_indices",

        {},

    ).items():

        for index in indices:

            index = int(index)



            if 0 <= index < len(feature_names):

                output[str(feature_names[index])] = canonical_domain(domain)



    return output





def reconstruct_union_test_matrix(

    reconstructed: Mapping[str, Any],

    run_dir: pathlib.Path,

    cache_path: pathlib.Path,

    *,

    force_recompute: bool,

) -> Dict[str, Any]:

    if cache_path.exists() and not force_recompute:

        print("\nLoading cached strict-OOF aligned test-set matrix:", cache_path)



        cached = np.load(

            cache_path,

            allow_pickle=True,

        )



        required_cache_keys = {

            "features",

            "domains",

            "values",

            "fold_presence_count",

            "test_n",

            "run_id",

        }

        missing_cache_keys = required_cache_keys - set(cached.files)

        if missing_cache_keys:

            raise RuntimeError(

                "The aligned-matrix cache lacks strict-OOF provenance keys: "

                f"{sorted(missing_cache_keys)}. Re-run with "

                "--force_recompute_matrix."

            )



        cached_test_n = int(

            np.asarray(cached["test_n"]).reshape(-1)[0]

        )

        cached_run_id = str(

            np.asarray(cached["run_id"], dtype=object).reshape(-1)[0]

        )



        if cached_test_n != len(reconstructed["X_test_raw"]):

            raise RuntimeError(

                "The aligned-matrix cache has a different test-set size. "

                "Re-run with --force_recompute_matrix."

            )



        if cached_run_id != run_dir.name:

            raise RuntimeError(

                "The aligned-matrix cache belongs to a different run "

                f"({cached_run_id} versus {run_dir.name}). Re-run with "

                "--force_recompute_matrix."

            )



        return {

            "features": normalize_object_array(cached["features"]),

            "domains": normalize_object_array(cached["domains"]),

            "values": cached["values"].astype(np.float32),

            "fold_presence_count": cached[

                "fold_presence_count"

            ].astype(int),

        }



    config = reconstructed["config"]

    X_test_raw = reconstructed["X_test_raw"]

    n_folds = int(config.get("n_folds", 5))



    fold_metadata: List[Dict[str, Any]] = []

    union_feature_set = set()

    domain_votes: Dict[str, Counter] = defaultdict(Counter)



    print("\n" + "=" * 100)

    print("ALIGNING FOLD-SPECIFIC TRANSFORMED HOLDOUT MATRICES")

    print("=" * 100)



    for fold_number in range(1, n_folds + 1):

        fold_dir = (

            run_dir

            / "fold_artifacts"

            / f"fold_{fold_number}"

        )



        selected_names = normalize_object_array(

            np.load(

                require_file(

                    fold_dir / "selected_feature_names.npy"

                ),

                allow_pickle=True,

            )

        )



        metadata = load_json(

            fold_dir / "selected_domain_metadata.json"

        )



        feature_domains = feature_domain_map_from_metadata(

            selected_names,

            metadata,

        )



        for feature in selected_names:

            union_feature_set.add(str(feature))



        for feature, domain in feature_domains.items():

            domain_votes[feature][domain] += 1



        fold_metadata.append(

            {

                "fold_number": fold_number,

                "fold_dir": fold_dir,

                "selected_names": selected_names,

            }

        )



    union_features = np.asarray(

        sorted(union_feature_set),

        dtype=object,

    )



    feature_to_union = {

        str(feature): index

        for index, feature in enumerate(union_features)

    }



    n_test = len(X_test_raw)

    n_union = len(union_features)



    value_sum = np.zeros(

        (n_test, n_union),

        dtype=np.float32,

    )

    fold_presence_count = np.zeros(

        n_union,

        dtype=np.int16,

    )



    for metadata in fold_metadata:

        fold_number = metadata["fold_number"]

        fold_dir = metadata["fold_dir"]

        selected_names = metadata["selected_names"]



        print(

            f"Transforming fold {fold_number}/{n_folds}: "

            f"{len(selected_names):,} features"

        )



        preprocessor = joblib.load(

            require_file(

                fold_dir / "preprocessor.joblib"

            )

        )



        variance_selector = joblib.load(

            require_file(

                fold_dir / "variance_selector.joblib"

            )

        )



        selected_indices = np.load(

            require_file(

                fold_dir / "selected_original_indices.npy"

            )

        ).astype(int)



        fold_values = transformed_matrix_for_fold(

            X_test_raw,

            preprocessor,

            variance_selector,

            selected_indices,

        )



        if fold_values.shape[1] != len(selected_names):

            raise RuntimeError(

                f"Fold {fold_number} transformed feature count does not "

                "match selected_feature_names.npy."

            )



        union_indices = np.asarray(

            [

                feature_to_union[str(feature)]

                for feature in selected_names

            ],

            dtype=int,

        )



        value_sum[:, union_indices] += fold_values

        fold_presence_count[union_indices] += 1



        del fold_values



    divisor = np.maximum(

        fold_presence_count.astype(np.float32),

        1.0,

    )



    union_values = value_sum / divisor[np.newaxis, :]



    final_domains: List[str] = []



    for feature in union_features:

        votes = domain_votes.get(str(feature), Counter())



        final_domains.append(

            votes.most_common(1)[0][0]

            if votes

            else "Other"

        )



    result = {

        "features": union_features,

        "domains": np.asarray(

            final_domains,

            dtype=object,

        ),

        "values": union_values,

        "fold_presence_count": fold_presence_count,

    }



    np.savez_compressed(

        cache_path,

        features=result["features"],

        domains=result["domains"],

        values=result["values"],

        fold_presence_count=result["fold_presence_count"],

        test_n=np.asarray(

            [len(X_test_raw)],

            dtype=np.int64,

        ),

        run_id=np.asarray(

            [run_dir.name],

            dtype=object,

        ),

    )



    print("Saved aligned test-matrix cache:", cache_path)

    print(f"Union transformed features: {n_union:,}")



    return result





