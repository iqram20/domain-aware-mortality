def load_importance_table(

    path: pathlib.Path,

) -> pd.DataFrame:

    table = pd.read_csv(require_file(path))



    required = {

        "feature",

        "domain",

        "mean_absolute_direct_attribution",

    }



    missing = required - set(table.columns)



    if missing:

        raise KeyError(

            f"{path.name} is missing columns: {sorted(missing)}"

        )



    table = table.copy()



    table["feature"] = table["feature"].astype(str)

    table["domain"] = table["domain"].map(canonical_domain)



    table["mean_absolute_direct_attribution"] = pd.to_numeric(

        table["mean_absolute_direct_attribution"],

        errors="coerce",

    ).fillna(0.0)



    if "pretty_feature" not in table.columns:

        table["pretty_feature"] = table["feature"].map(

            pretty_feature_name

        )

    else:

        # Recreate labels so this script always uses the current tidy labels.

        table["pretty_feature"] = table["feature"].map(

            pretty_feature_name

        )



    return table.sort_values(

        "mean_absolute_direct_attribution",

        ascending=False,

    ).reset_index(drop=True)





