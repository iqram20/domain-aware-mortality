def parse_args(

    argv: Optional[Sequence[str]] = None,

) -> argparse.Namespace:

    parser = argparse.ArgumentParser(

        allow_abbrev=False,

        description=(

            "Create the final temporal-safe strict-OOF supplementary XAI input "

            "correlation and clustering figure."

        ),

    )



    parser.add_argument(

        "--run_dir",

        type=pathlib.Path,

        default=DEFAULT_RUN_DIR,

    )



    parser.add_argument(

        "--pipeline_module",

        type=pathlib.Path,

        default=DEFAULT_PIPELINE_MODULE,

    )



    parser.add_argument(

        "--data_path",

        type=pathlib.Path,

        default=DEFAULT_DATA_PATH,

    )



    parser.add_argument(

        "--output_dir",

        type=pathlib.Path,

        default=None,

    )



    parser.add_argument(

        "--top_k",

        type=int,

        default=TOP_K,

    )



    parser.add_argument(

        "--force_recompute_matrix",

        action="store_true",

        help=(

            "Recompute the fold-aligned transformed test-set matrix instead "

            "of loading the saved cache."

        ),

    )



    raw_arguments = list(

        sys.argv[1:]

        if argv is None

        else argv

    )



    filtered_arguments: List[str] = []

    skip_next = False



    for argument in raw_arguments:

        if skip_next:

            skip_next = False

            continue



        if argument in {"-f", "--f"}:

            skip_next = True

            continue



        if (

            argument.startswith("-f=")

            or argument.startswith("--f=")

        ):

            continue



        filtered_arguments.append(argument)



    args, unknown = parser.parse_known_args(

        filtered_arguments

    )



    if unknown:

        print(

            "Ignoring unrecognized Jupyter/IPython arguments:",

            " ".join(map(str, unknown)),

        )



    return args





def main() -> None:

    args = parse_args()



    output_dir = (

        args.output_dir

        if args.output_dir is not None

        else args.run_dir / DEFAULT_OUTPUT_SUBDIR

    )



    run_analysis(

        run_dir=args.run_dir,

        pipeline_module_path=args.pipeline_module,

        data_path=args.data_path,

        output_dir=output_dir,

        top_k=args.top_k,

        force_recompute_matrix=args.force_recompute_matrix,

    )





if __name__ == "__main__":

    main()