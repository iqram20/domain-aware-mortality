def build_analysis_tables(

    union_matrix: Mapping[str, Any],

    importance_table: pd.DataFrame,

    *,

    top_k: int,

) -> Dict[str, Any]:

    features = union_matrix["features"].astype(str)

    domains = union_matrix["domains"].astype(str)

    values = union_matrix["values"].astype(np.float64)



    feature_to_index = {

        feature: index

        for index, feature in enumerate(features)

    }



    available_importance = importance_table[

        importance_table["feature"].isin(feature_to_index)

    ].copy()



    if available_importance.empty:

        raise RuntimeError(

            "None of the strict-OOF attributed features were present in "

            "the aligned transformed test-set matrix."

        )



    duplicated_labels = (

        available_importance["pretty_feature"]

        .astype(str)

        .duplicated(keep=False)

    )

    if duplicated_labels.any():

        duplicate_table = available_importance.loc[

            duplicated_labels,

            ["feature", "pretty_feature"],

        ]

        print(

            "Warning: duplicate display labels remain after feature-label "

            "normalization:\n"

            + duplicate_table.to_string(index=False)

        )



    if len(available_importance) < top_k:

        print(

            f"Warning: only {len(available_importance)} attributed features "

            f"were present in the aligned test matrix."

        )



    top_table = available_importance.head(top_k).copy()



    top_indices = np.asarray(

        [

            feature_to_index[feature]

            for feature in top_table["feature"]

        ],

        dtype=int,

    )



    X_top = pd.DataFrame(

        values[:, top_indices],

        columns=top_table["feature"],

    )



    feature_correlation = X_top.corr(

        method="spearman"

    ).fillna(0.0)



    np.fill_diagonal(

        feature_correlation.values,

        1.0,

    )



    distance = (

        1.0

        - np.abs(

            feature_correlation.to_numpy(

                dtype=float

            )

        )

    )



    distance = np.clip(

        distance,

        0.0,

        2.0,

    )


    distance = (

        distance

        + distance.T

    ) / 2.0



    np.fill_diagonal(

        distance,

        0.0,

    )



    condensed = squareform(

        distance,

        checks=False,

    )



    feature_linkage = linkage(

        condensed,

        method=CLUSTER_LINKAGE_METHOD,

    )



    leaf_order = dendrogram(

        feature_linkage,

        no_plot=True,

    )["leaves"]



    ordered_features = [

        top_table.iloc[index]["feature"]

        for index in leaf_order

    ]



    ordered_labels = [

        pretty_feature_name(feature)

        for feature in ordered_features

    ]



    ordered_correlation = feature_correlation.loc[

        ordered_features,

        ordered_features,

    ]



    # Domain-level input summaries are formed by z-scoring each selected

    # transformed feature across the full held-out test set and averaging the

    # standardized values within each domain.

    feature_mean = np.nanmean(

        values,

        axis=0,

    )



    feature_sd = np.nanstd(

        values,

        axis=0,

    )



    feature_sd = np.where(

        feature_sd <= 1e-12,

        1.0,

        feature_sd,

    )



    values_z = (

        values - feature_mean

    ) / feature_sd



    domain_summary: Dict[str, np.ndarray] = {}



    for domain in sorted(set(domains)):

        indices = np.where(

            domains == domain

        )[0]



        if len(indices) == 0:

            continue



        domain_summary[domain] = np.nanmean(

            values_z[:, indices],

            axis=1,

        )



    domain_summary_df = pd.DataFrame(

        domain_summary

    )



    domain_correlation = domain_summary_df.corr(

        method="spearman"

    ).fillna(0.0)



    np.fill_diagonal(

        domain_correlation.values,

        1.0,

    )



    domain_attribution = (

        importance_table.groupby(

            "domain",

            as_index=False,

        )

        .agg(

            n_union_features=(

                "feature",

                "size",

            ),

            summed_mean_absolute_attribution=(

                "mean_absolute_direct_attribution",

                "sum",

            ),

        )

    )



    total = float(

        domain_attribution[

            "summed_mean_absolute_attribution"

        ].sum()

    )



    if total <= 0:

        raise ValueError(

            "Total Uniform DARN attribution is zero."

        )



    domain_attribution[

        "direct_attribution_percent"

    ] = (

        domain_attribution[

            "summed_mean_absolute_attribution"

        ]

        / total

        * 100.0

    )



    domain_attribution[

        "display_domain"

    ] = domain_attribution[

        "domain"

    ].map(display_domain)



    domain_attribution = domain_attribution.sort_values(

        "direct_attribution_percent",

        ascending=True,

    ).reset_index(drop=True)



    return {

        "top_table": top_table,

        "ordered_features": ordered_features,

        "ordered_labels": ordered_labels,

        "ordered_correlation": ordered_correlation,

        "feature_linkage": feature_linkage,

        "domain_correlation": domain_correlation,

        "domain_attribution": domain_attribution,

    }





